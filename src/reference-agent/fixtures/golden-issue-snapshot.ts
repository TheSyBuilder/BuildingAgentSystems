interface FixtureInput {
  readonly number: number;
  readonly title: string;
  readonly body: string;
  readonly authorLogin: string;
  readonly authorAssociation: AuthorAssociation;
  readonly createdAt: string;
  readonly state?: "open" | "closed";
  readonly comments?: readonly IssueComment[];
  readonly expected: GoldenTriage;
}

function fixture(input: FixtureInput): GoldenIssueFixture {
  const comments = input.comments ?? [];
  const updatedAt = comments.at(-1)?.createdAt ?? input.createdAt;

  return {
    issue: {
      id: `relaydesk-issue-${input.number}`,
      number: input.number,
      title: input.title,
      body: input.body,
      authorLogin: input.authorLogin,
      authorAssociation: input.authorAssociation,
      createdAt: input.createdAt,
      updatedAt,
      state: input.state ?? "open",
      labels: [],
      comments,
    },
    expected: input.expected,
  };
}

function comment(
  issueNumber: number,
  index: number,
  authorLogin: string,
  authorAssociation: AuthorAssociation,
  createdAt: string,
  body: string,
): IssueComment {
  return {
    id: `relaydesk-comment-${issueNumber}-${index}`,
    authorLogin,
    authorAssociation,
    createdAt,
    body,
  };
}

